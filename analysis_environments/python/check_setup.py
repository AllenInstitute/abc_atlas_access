"""Check that the Python environment can read the ABC Atlas cloud data.

Reads the gene table and a tiny slice of expression from the public WMB-10Xv3 store, the same way the
scripts generated by the ABC Atlas do.

    uv run python check_setup.py
"""
import io
import time
from importlib.metadata import version

import numpy as np
import obstore
import pandas as pd
import zarr
from obstore.store import GCSStore
from zarr.storage import ObjectStore

BUCKET = "abc-atlas-data-refactor"
PREFIX = "refactor/WMB-10Xv3/20230630/WMB-10Xv3-log2"

t0 = time.time()
bucket = GCSStore(BUCKET, skip_signature=True)  # public bucket: no credentials needed
var = pd.read_parquet(io.BytesIO(bytes(obstore.get(bucket, f"{PREFIX}.var.parquet").bytes())))
store = ObjectStore(GCSStore(BUCKET, prefix=f"{PREFIX}.zarr", skip_signature=True), read_only=True)
X = zarr.open_group(store, mode="r")["X"]
gene = int(var.loc[var["gene_symbol"] == "Slc17a7", "gene_index"].iloc[0])
x = X[:1000, gene]
print(f"anndata {version('anndata')}, zarr {version('zarr')}")
print(f"read {len(var):,} genes and X[:1000, Slc17a7] (mean {np.mean(x):.3f}) from gs://{BUCKET} "
      f"in {time.time() - t0:.1f}s")
print("OK: the Python environment can read the ABC Atlas cloud data")
